public class Akumulasi {

    public static void main(String[] args) {
        int jumlah=0;
        for(int i = 1;i <= 10; i++){
            jumlah = jumlah + i;
            System.out.println("Iterasi ke-" + i + " | nilai jumlah = " + jumlah);
        }
        
        
    }
}
